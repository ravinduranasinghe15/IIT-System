// Generates the fixed DEMO terminal report used for the live demo, plus the matching hard-coded data module.
//   node scripts/generate-demo-report.mjs
// Writes public/documents/MTS-Demo-Terminal-Report.xlsx and src/data/demo-import.ts (same rows, single source of truth).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const LETTER_VALUES = {};
(() => {
  let v = 10;
  for (const ch of "ABCDEFGHIJKLMNOPQRSTUVWXYZ") {
    if (v % 11 === 0) v++;
    LETTER_VALUES[ch] = v;
    v++;
  }
})();
const checkDigit = (s) => {
  let sum = 0;
  for (let i = 0; i < 10; i++) sum += (/[A-Z]/.test(s[i]) ? LETTER_VALUES[s[i]] : Number(s[i])) * 2 ** i;
  return (sum % 11) % 10;
};
const mk = (prefix, serial) => {
  const body = prefix + String(serial).padStart(6, "0");
  return body + checkDigit(body);
};

const D = "2026-11-13";
const t = (hhmm) => (hhmm ? `${D} ${hhmm}` : "");

const HEADERS = ["Container No", "Size", "Origin", "Destination", "Truck", "Trailer", "Driver", "Load Time", "Discharge Time", "Status"];
